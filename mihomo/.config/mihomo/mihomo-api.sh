#!/bin/bash
# NOTE: despite the shebang, this file is *sourced* (from ~/.zshrc), so every function
# here must run in both bash and zsh. Two traps that have already bitten:
#   - `path` is a special zsh parameter tied to $PATH: never `read -r path`
#   - zsh arrays are 1-indexed, bash's are 0-indexed: prefer plain scalars
MIHOMO_SERVICE_URL="http://127.0.0.1:7890"
MIHOMO_CONFIG_PATH="${MIHOMO_CONFIG_PATH:-$HOME/.config/mihomo}"
MIHOMO_DNS_VIRTUAL_IP="198.18.0.2"
MIHOMO_CONTROLLER_URL="http://127.0.0.1:9090" # matches external-controller in mihomo.yaml
NETWORK_SERVICE="Wi-Fi"                       # Consider making this dynamic in the future

# Derived config paths, all rooted at MIHOMO_CONFIG_PATH and fixed at load time.
# To relocate the config tree, set MIHOMO_CONFIG_PATH (or any of these) before
# sourcing this file. render_config and startproxy all read these globals.
MIHOMO_TEMPLATE_PATH="$MIHOMO_CONFIG_PATH/mihomo.yaml"
MIHOMO_PROVIDERS_PATH="$MIHOMO_CONFIG_PATH/providers.yaml"
MIHOMO_RUNTIME_PATH="$MIHOMO_CONFIG_PATH/mihomo_runtime.yaml"
# Generated by render_provider_tweaks and merged last, so it overrides the template.
MIHOMO_TWEAKS_PATH="$MIHOMO_CONFIG_PATH/provider-tweaks.yaml"
# The spec of *what may be lifted* out of a provider's dns: block. Hand-written and
# tracked, unlike the .yaml above which is generated from it. See the file's header.
MIHOMO_TWEAKS_PROGRAM="$MIHOMO_CONFIG_PATH/provider-tweaks.yq"
# Outcome of the last render_provider_tweaks call: found | missing | multi.
# "missing" means no provider dns: was available (fresh machine), so startproxy
# nudges the user to restart once the subscription has been fetched.
MIHOMO_TWEAKS_STATE="missing"

# Single retry budget for every poll in the script (readiness, blocked site,
# and connection checks). Change here to tune how long mihomo is allowed to settle.
MIHOMO_RETRY_TRIES=10
MIHOMO_RETRY_DELAY=1

function is_macos() {
    [[ "$(uname -s)" == "Darwin" ]]
}

# ---------------------------------------------------------------------------
# Provider DNS tweaks
#
# A subscription is a full Clash config, but mihomo reads only `proxies:` out of
# a proxy-provider document (adapter/provider/provider.go: ProxySchema). The
# provider's `dns:` block — notably its own resolver for the node domains — is
# discarded. render_provider_tweaks() lifts the few keys that matter into
# MIHOMO_TWEAKS_PATH, which render_config merges last so it wins.
#
#   lifted : dns.nameserver -> dns.proxy-server-nameserver (node lookups only)
#            dns.use-hosts, dns.fake-ip-filter
#            dns.proxy-server-nameserver and root `hosts`, if a provider ships them
#   dropped: listen, enable, enhanced-mode, fake-ip-range, default-nameserver
#
# The keys and their mapping live in provider-tweaks.yq; this function only locates
# the provider cache and applies the spec. The fresh-machine fallback (the airport's
# resolvers, used before the subscription has ever been fetched) lives in
# providers.yaml like the rest of the provider-specific spec — mihomo.yaml stays a
# shareable template.
#
# Rationale and sources: docs/research/mihomo-provider-dns-tweaks.md
# ---------------------------------------------------------------------------
function render_provider_tweaks() {
    # NOT `path`: this file is sourced from .zshrc, and in zsh `path` is a special
    # parameter tied to $PATH — `read -r path` would replace $PATH with the file
    # path and every later `yq` in this function would be "command not found".
    local f cache_path line source_file="" overlay="" stripped skipped
    local fallback applied
    # Plain scalars rather than an array keeps this portable: zsh arrays are
    # 1-indexed while bash's are 0-indexed, and this file runs in both shells.
    local first_cache="" other_caches="" cache_count=0

    MIHOMO_TWEAKS_STATE="missing"

    if [[ ! -f "$MIHOMO_TWEAKS_PROGRAM" ]]; then
        echo "Error: tweak spec not found at $MIHOMO_TWEAKS_PROGRAM" >&2
        return 1
    fi

    # Cache paths come from providers.yaml rather than a glob, so a cache file
    # left behind by a removed subscription cannot leak into the runtime config.
    while IFS= read -r cache_path; do
        [[ -n "$cache_path" ]] || continue
        case "$cache_path" in
            /*) f="$cache_path" ;;
            *) f="$MIHOMO_CONFIG_PATH/${cache_path#./}" ;;
        esac
        [[ -f "$f" ]] || continue
        [[ "$(yq -r 'has("dns")' "$f" 2>/dev/null)" == "true" ]] || continue
        cache_count=$((cache_count + 1))
        if [[ -z "$first_cache" ]]; then
            first_cache="$f"
        else
            other_caches+="$f"$'\n'
        fi
    done < <(yq -r '.proxy-providers | to_entries[] | .value.path // ""' "$MIHOMO_PROVIDERS_PATH" 2>/dev/null)

    while IFS= read -r line; do
        [[ -n "$line" ]] || continue
        echo "Warning: proxy-provider '$line' sets no path:, so its cache cannot be located" >&2
        echo "         and its dns: is not lifted." >&2
    done < <(yq -r '.proxy-providers | to_entries[] | select((.value.path // "") == "") | .key' "$MIHOMO_PROVIDERS_PATH" 2>/dev/null)

    if (( cache_count == 0 )); then
        printf '{}\n' >"$MIHOMO_TWEAKS_PATH"
        return 0
    fi
    source_file="$first_cache"

    if (( cache_count > 1 )); then
        echo "Warning: more than one proxy-provider ships a dns: block, and the multi-provider" >&2
        echo "         policy is not designed yet. Using $(basename "$source_file"), ignoring:" >&2
        while IFS= read -r line; do
            [[ -n "$line" ]] || continue
            echo "           $line" >&2
        done <<<"$other_caches"
    fi

    # The spec file owns the rules; this function only decides which file to feed
    # it and what to do with the result. `_skipped` is a report channel, not config.
    if ! overlay=$(yq --from-file "$MIHOMO_TWEAKS_PROGRAM" "$source_file" 2>/dev/null); then
        echo "Warning: failed to apply $(basename "$MIHOMO_TWEAKS_PROGRAM") to" >&2
        echo "         $(basename "$source_file"); keeping the providers.yaml fallback." >&2
        printf '{}\n' >"$MIHOMO_TWEAKS_PATH"
        return 0
    fi

    if ! stripped=$(printf '%s\n' "$overlay" | yq 'del(._skipped)' 2>/dev/null); then
        printf '{}\n' >"$MIHOMO_TWEAKS_PATH"
    else
        printf '%s\n' "$stripped" >"$MIHOMO_TWEAKS_PATH"
    fi

    skipped=$(printf '%s\n' "$overlay" | yq -r '._skipped[]?' 2>/dev/null)
    if [[ -n "$skipped" ]]; then
        echo "Warning: skipping circular DNS resolver(s) from $(basename "$source_file")," >&2
        echo "         which would need the very proxy they resolve for:" >&2
        while IFS= read -r line; do
            [[ -n "$line" ]] || continue
            echo "           $line" >&2
        done <<<"$skipped"
    fi

    # No resolver lifted means the providers.yaml fallback is still what runs, so
    # report that as missing rather than found and let startproxy nudge a restart.
    if [[ "$(yq -r '(.dns."proxy-server-nameserver" // []) | length' "$MIHOMO_TWEAKS_PATH" 2>/dev/null)" == "0" ]]; then
        return 0
    fi

    if (( cache_count > 1 )); then
        MIHOMO_TWEAKS_STATE="multi"
    else
        MIHOMO_TWEAKS_STATE="found"
    fi

    # The generated file silently overrides the providers.yaml fallback, so this is
    # the only place that difference becomes visible.
    # Reached only when a resolver was lifted, so no need to re-test for emptiness.
    applied=$(yq -r '.dns."proxy-server-nameserver"[]?' "$MIHOMO_TWEAKS_PATH" 2>/dev/null)
    echo "render: node DNS from $(basename "$source_file"):"
    while IFS= read -r line; do
        echo "          $line"
    done <<<"$applied"
    fallback=$(yq -r '.dns."proxy-server-nameserver"[]?' "$MIHOMO_PROVIDERS_PATH" 2>/dev/null)
    if [[ "$(sort <<<"$applied")" != "$(sort <<<"$fallback")" ]]; then
        echo "render: NOTE - that differs from the dns: fallback in providers.yaml." >&2
        echo "        Update it so a machine with no cache yet still works." >&2
    fi
}

# Render the runtime config: deep-merge the template, providers.yaml (providers win),
# then the generated provider tweaks (which win over both; arrays replace, not append).
# Template stays a shareable skeleton; real subscription URLs/specs live in providers.yaml.
# The rendered file is rejected unless `mihomo -t` accepts it, so a bad merge never
# reaches the routing path.
function render_config() {
    if [[ ! -f "$MIHOMO_PROVIDERS_PATH" ]]; then
        echo "Error: Providers file not found at $MIHOMO_PROVIDERS_PATH" >&2
        return 1
    fi

    render_provider_tweaks

    if ! yq eval-all 'select(fileIndex == 0) * select(fileIndex == 1) * select(fileIndex == 2)' \
        "$MIHOMO_TEMPLATE_PATH" "$MIHOMO_PROVIDERS_PATH" "$MIHOMO_TWEAKS_PATH" >"$MIHOMO_RUNTIME_PATH"; then
        echo "Error: Failed to render runtime config." >&2
        rm -f "$MIHOMO_RUNTIME_PATH" # Clean up partial output.
        return 1
    fi

    # `mihomo -t` parses the whole config, so a malformed lifted dns: (invalid YAML,
    # a wrong type, a field the core rejects) is caught here rather than at start.
    # It does NOT check that the resolvers answer: an unresolvable
    # proxy-server-nameserver host still passes `-t` and only fails at dial time.
    local test_output
    if ! test_output=$(mihomo -t -d "$MIHOMO_CONFIG_PATH" -f "$MIHOMO_RUNTIME_PATH" 2>&1); then
        echo "Error: rendered config failed 'mihomo -t'; not starting." >&2
        printf '%s\n' "$test_output" >&2
        rm -f "$MIHOMO_RUNTIME_PATH"
        return 1
    fi

    echo "Runtime config written to $MIHOMO_RUNTIME_PATH"
}

function setproxy() {
    export {http,https,ftp,all}_proxy="$MIHOMO_SERVICE_URL"
    export {HTTP,HTTPS,FTP,ALL}_PROXY="$MIHOMO_SERVICE_URL"
}

function unsetproxy() {
    unset {http,https,ftp,all}_proxy
    unset {HTTP,HTTPS,FTP,ALL}_PROXY
}

# Verify the running mihomo on demand: API controller up, a blocked site reachable
# through the mixed port, the dashboard served, and (macOS) system DNS pointed at
# mihomo's virtual IP. Retries briefly so mihomo can settle and providers/health-
# checks warm up. The runbook's proxy-phase CHECKs call this directly.
function statusproxy() {
    local failures=0 tries="$MIHOMO_RETRY_TRIES" delay="$MIHOMO_RETRY_DELAY"

    # 1. Process + API controller (readiness).
    if ! wait_for "$tries" "$delay" pgrep -x mihomo; then
        echo "status: FAIL - mihomo is not running"
        return 1
    fi
    if ! wait_for "$tries" "$delay" \
        curl -fs -o /dev/null "$MIHOMO_CONTROLLER_URL/version"; then
        echo "status: FAIL - API controller not responding on $MIHOMO_CONTROLLER_URL"
        return 1
    fi
    echo "status: ok - mihomo running, API controller up"

    # 2. A blocked site must be reachable through the mixed port.
    if ! wait_for "$tries" "$delay" \
        curl -fs -o /dev/null -x "$MIHOMO_SERVICE_URL" https://www.youtube.com; then
        echo "status: FAIL - blocked site not reachable through $MIHOMO_SERVICE_URL"
        failures=$((failures + 1))
    else
        echo "status: ok - proxy forwards to the open internet"
    fi

    # 3.  (external-ui, auto-downloaded via external-ui-url on first run).
    if ! curl -fsS -o /dev/null "$MIHOMO_CONTROLLER_URL/ui/" 2>/dev/null; then
        echo "status: FAIL - dashboard not served at $MIHOMO_CONTROLLER_URL/ui/"
        failures=$((failures + 1))
    else
        echo "status: ok - dashboard served"
    fi

    # 4. macOS only: system DNS pointed at mihomo's virtual IP.
    if is_macos; then
        if scutil --dns 2>/dev/null | grep -q "$MIHOMO_DNS_VIRTUAL_IP"; then
            echo "status: ok - system DNS routed to mihomo"
        else
            echo "status: FAIL - system DNS not pointed at $MIHOMO_DNS_VIRTUAL_IP"
            failures=$((failures + 1))
        fi
    fi

    if ((failures > 0)); then
        echo "status: $failures check(s) failed"
        return 1
    fi
    echo "status: all checks passed"
    return 0
}

# Run a probe until it succeeds or the budget is exhausted. The probe is a command
# (no eval): pass it as the remaining arguments, e.g. `wait_for 10 2 pgrep -x mihomo`.
# One retry loop serves every wait in the script — process, controller, blocked site.
function wait_for() {
    local tries="$1" delay="$2" i
    shift 2
    for ((i = 1; i <= tries; i++)); do
        if "$@" >/dev/null 2>&1; then
            return 0
        fi
        sleep "$delay"
    done
    return 1
}

function startproxy() {
    # 1. Guard against duplicate mihomo instances.
    if pgrep -x mihomo >/dev/null; then
        echo "mihomo has already started."
        return 1
    fi

    # 2. Render the runtime config from the template + providers into the shared
    # MIHOMO_RUNTIME_PATH (derived at load) that the launch step uses.
    if ! render_config; then
        return 1
    fi

    # 3. Require sudo; on macOS, point DNS to mihomo virtual ip.
    if ! sudo -v; then
        echo "sudo authentication failed."
        return 1
    fi

    if is_macos; then
        sudo networksetup -setdnsservers "$NETWORK_SERVICE" "$MIHOMO_DNS_VIRTUAL_IP"
    fi
    # -d sets Home Dir to the config dir: relative provider `path:` (./proxy_providers/...),
    # cache.db and external-ui all live under MIHOMO_CONFIG_PATH. Since the config dir
    # matches mihomo's default home dir, -d is technically redundant — kept for explicitness.
    sudo -b mihomo -d "$MIHOMO_CONFIG_PATH" -f "$MIHOMO_RUNTIME_PATH" >/dev/null 2>&1 &

    echo "mihomo started with config: $MIHOMO_RUNTIME_PATH"

    # Run the full statusproxy checks (readiness, blocked site, dashboard, DNS) so
    # startproxy only returns 0 when mihomo is fully working. statusproxy's first
    # step waits for the process + controller, so no separate boot gate is needed.
    if ! statusproxy; then
        echo "startproxy: FAILED - verify the statusproxy lines above" >&2
        return 1
    fi

    # Fresh machine: render_config ran before mihomo had ever fetched the
    # subscription, so no provider dns: existed to lift. Startup is still good
    # (the providers.yaml fallback handles node DNS) — this is an action, not a failure.
    if [[ "$MIHOMO_TWEAKS_STATE" == "missing" ]]; then
        echo "startproxy: note - no provider dns: was available to lift, so the fallback"
        echo "            in providers.yaml is in use. Restart the proxy (stopproxy; startproxy)"
        echo "            once the subscription has been fetched, to pick up the airport's own."
    fi

    echo "startproxy: mihomo fully working (all statusproxy checks passed)"
    return 0
}

function stopproxy() {
    if [[ -z $(pgrep -x mihomo) ]]; then
        echo "mihomo is not running"
        return 1
    fi

    # kill mihomo process. On macOs, reset system dns config to default
    sudo kill "$(sudo pgrep -x mihomo)"
    if is_macos; then
        sudo networksetup -setdnsservers "$NETWORK_SERVICE" Empty
    fi
}
